/** Request transport classification used by Start request traces and metrics. */
export type StartRequestTraceTransport = "ssr" | "rpc" | "action" | "unknown";

/** Final outcome recorded for a Start request trace. */
export type StartRequestTraceStatus = "success" | "failure" | "cancelled";

/** Failure category used by diagnostics without exposing raw causes. */
export type StartRequestTraceFailureKind =
  | "domain"
  | "validation"
  | "protocol"
  | "transport"
  | "defect"
  | "interruption";

/** Lifecycle state for streamed SSR response traces. */
export type StartRequestTraceStreamState = "open" | "closed" | "cancelled" | "errored";

/** Lifecycle state for the request runtime fiber recorded in traces. */
export type StartRequestTraceFiberStatus = "running" | "done" | "interrupted" | "failed";

/** Redacted or safe header value captured for request/response diagnostics. */
export interface StartRequestTraceHeader {
  /** Lowercase or platform-preserved header name. */
  readonly name: string;
  /** Header value, redacted for sensitive header names. */
  readonly value: string;
}

/** Redacted request cookie captured for diagnostics. */
export interface StartRequestTraceCookie {
  /** Decoded cookie name. */
  readonly name: string;
  /** Redacted decoded cookie value. */
  readonly value: string;
}

/** Request snapshot at the boundary of a Start request handler. */
export interface StartRequestTraceRequest {
  /** Correlation id generated by Start or read from the incoming request header. */
  readonly id?: string;
  /** Incoming W3C traceparent header when present. */
  readonly traceparent?: string;
  /** HTTP request method. */
  readonly method: string;
  /** Full request URL. */
  readonly url: string;
  /** URL pathname used for request metrics. */
  readonly path: string;
  /** Start transport that handled the request. */
  readonly transport: StartRequestTraceTransport;
  /** Safe request headers included when any were captured. */
  readonly headers?: ReadonlyArray<StartRequestTraceHeader>;
  /** Redacted request cookies included when any were present. */
  readonly cookies?: ReadonlyArray<StartRequestTraceCookie>;
}

/** Response snapshot emitted with a completed Start request trace. */
export interface StartRequestTraceResponse {
  /** Final HTTP status. */
  readonly status: number;
  /** Final HTTP status text when the platform response supplied one. */
  readonly statusText?: string;
  /** Safe response headers included when any were captured. */
  readonly headers?: ReadonlyArray<StartRequestTraceHeader>;
  /** Count of Set-Cookie headers when the platform exposes them. */
  readonly setCookieCount?: number;
}

