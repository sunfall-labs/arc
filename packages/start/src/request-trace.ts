/** Complete best-effort observability record emitted for a handled Start request. */
export interface StartRequestTrace {
  /** Request boundary snapshot. */
  readonly request: StartRequestTraceRequest;
  /** Response boundary snapshot when a response was produced. */
  readonly response?: StartRequestTraceResponse;
  /** Request-scoped services provided by Start. */
  readonly services: ReadonlyArray<string>;
  /** Route planning summary for SSR requests. */
  readonly routePlan?: StartRequestTraceRoutePlan;
  /** Resources touched during the request. */
  readonly resources: ReadonlyArray<StartRequestTraceResource>;
  /** Collections touched during route preload, registration, or dehydration. */
  readonly collections: ReadonlyArray<StartRequestTraceCollection>;
  /** Server function calls observed during the request. */
  readonly serverFunctions: ReadonlyArray<StartRequestTraceServerFunction>;
  /** Start action calls observed during the request. */
  readonly actions: ReadonlyArray<StartRequestTraceAction>;
  /** Request runtime fibers observed during the request. */
  readonly fibers: ReadonlyArray<StartRequestTraceFiber>;
  /** Stream lifecycle records observed during the request. */
  readonly streams: ReadonlyArray<StartRequestTraceStream>;
  /** Final request outcome. */
  readonly status: StartRequestTraceStatus;
  /** Failure kind when the request failed or was interrupted. */
  readonly failureKind?: StartRequestTraceFailureKind;
  /** Request runtime teardown diagnostics. */
  readonly teardown?: StartRequestTraceTeardown;
}

/** Route preload and hydration summary attached to SSR request traces. */
